const pickDefaults = (defaults: VeraContent, fields: string[]): VeraContent =>
  Object.fromEntries(fields.map((field) => [field, defaults[field]]).filter(([, value]) => value !== undefined));

const omitDefaults = (defaults: VeraContent, fields: string[]): VeraContent => {
  const omitted = new Set(fields);
  return Object.fromEntries(Object.entries(defaults).filter(([field]) => !omitted.has(field)));
};

